thu = int(input("nhập thứ muốn nhập(1 ->7): "))
if thu == 1:
    print(f"{thu}:sunday")
elif thu == 2:
    print(f'{thu}:monday')
elif thu == 3:
    print(f"{thu}:tuesday")
elif thu == 4:
    print(f"{thu}:wednesday")
elif thu == 5:
    print(f"{thu}:thursday")
elif thu == 6:
    print(f"{thu}:friday")
elif thu == 7:
    print(f"{thu}:saturday")
else:
    print("không hợp lệ vui lòng nhập lại")