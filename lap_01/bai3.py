thu = int(input("nhap so thu trong tuan (1->7): "))
if thu == 1:
    print("sunday")
elif thu == 2:
    print("monday")
elif thu == 3:
    print("tuesday")
elif thu == 4:
    print("wednesday.")
elif thu == 5:
    print("thursday")
elif thu == 6:
    print("friday")
elif thu == 7:
    print("saturday")
else:
    print("vui long nhap lai.")